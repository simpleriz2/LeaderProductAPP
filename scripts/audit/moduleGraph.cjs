// Static import evidence, including literal dynamic imports/require; not a runtime reachability proof.
const ts = require('typescript');
const fs = require('node:fs');
const path = require('node:path');
const roots = ['app', 'src', 'context', 'hooks', 'utils', 'components', 'modules', 'plugins', 'app.config.ts', 'index.js'];
const files = [];
function walk(dir) {
  if (!fs.existsSync(dir)) return;
  if(fs.statSync(dir).isFile()) { files.push(dir); return; }
  for (const item of fs.readdirSync(dir, { withFileTypes: true })) {
    if (['node_modules', 'build', '.git'].includes(item.name)) continue;
    const p = path.join(dir, item.name);
    if (item.isDirectory()) walk(p);
    else if (/\.[jt]sx?$/.test(p)) files.push(p);
  }
}
roots.forEach(walk);
const domain = p => p.match(/^src\/features\/([^/]+)/)?.[1] || 'platform';
const edges = [];
const dynamic = [];
for (const file of files.sort()) {
  const source = ts.createSourceFile(file, fs.readFileSync(file, 'utf8'), ts.ScriptTarget.Latest, true);
  function add(node, value, kind) {
    if (!value || !ts.isStringLiteralLike(value)) { dynamic.push({ file, line: source.getLineAndCharacterOfPosition(node.pos).line + 1 }); return; }
    const specifier = value.text;
    const target = specifier.startsWith('@/') ? specifier.slice(2) : specifier.startsWith('.') ? path.normalize(path.join(path.dirname(file), specifier)) : null;
    edges.push({ file, specifier, target, kind, from: domain(file), to: target ? domain(target) : 'external' });
  }
  function visit(n) {
    if (ts.isImportDeclaration(n) || ts.isExportDeclaration(n)) { if(n.moduleSpecifier) add(n, n.moduleSpecifier, 'static'); }
    if (ts.isCallExpression(n) && (n.expression.kind === ts.SyntaxKind.ImportKeyword || (ts.isIdentifier(n.expression) && n.expression.text === 'require'))) add(n, n.arguments[0], 'dynamic');
    ts.forEachChild(n, visit);
  }
  visit(source);
}
const violations = edges.filter(e => e.from !== 'platform' && e.to !== 'platform' && e.to !== 'external' && e.from !== e.to);
const externalPackages = {};
for(const edge of edges.filter(e=>e.target === null)) {
  const name = edge.specifier.startsWith('@') ? edge.specifier.split('/').slice(0,2).join('/') : edge.specifier.split('/')[0];
  (externalPackages[name] ||= new Set()).add(edge.file);
}
const report = { externalPackages: Object.fromEntries(Object.entries(externalPackages).sort().map(([name,paths])=>[name,[...paths]])), routes: files.filter(f=>f.startsWith('app/')), method: 'TypeScript AST; paths normalized, extensions/platform/index not resolved; includes type imports; dynamic non-literals require manual review', files: files.length, edges: edges.length, crossFeatureImports: violations, nonLiteralImports: dynamic };
fs.writeFileSync('docs/leader-product-2/module-graph.json', JSON.stringify(report, null, 2)+'\n');
console.log(`${files.length} files; ${edges.length} imports; ${violations.length} cross-feature imports; ${dynamic.length} nonliteral imports`);

const pkg=JSON.parse(fs.readFileSync('package.json','utf8'));
const expo=Object.keys({...pkg.dependencies,...pkg.devDependencies}).filter(n=>n==='expo'||n.startsWith('expo-')||n.startsWith('@expo/')).sort();
const lines=['# Inherited Expo dependency disposition','', 'Generated by scripts/audit/moduleGraph.cjs from declared dependencies and TypeScript AST imports. Plugin registration/native autolinking can make a package reachable without a JS import. No package is declared dead from this report. All remain legacy dependencies pending scenario/native replacement evidence; none is implicitly approved for the target host.','', '| Dependency | Static importing files | Current disposition |','| --- | ---: | --- |'];
for(const name of expo) lines.push(`| ${name} | ${(externalPackages[name]||new Set()).size} | Legacy only; replacement/removal review pending |`);
lines.push('', 'Standalone platform-host package.json has no Expo dependencies. DEV exception does not authorize SDK/runtime components. Existing config plugins, Kotlin Help/geometry/audio, tracking, outbox, notifications and recovery must be inventoried separately before removal. Native credentials adapter exists in the new host, but does not yet replace legacy auth storage.', '', 'Route file inventory (source existence, not functional/device parity):', '');
for(const file of report.routes) lines.push(`- ${file}`);
fs.writeFileSync('docs/leader-product-2/expo-and-routes.md',lines.join('\n')+'\n');
